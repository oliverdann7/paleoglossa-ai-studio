import { useSyncExternalStore } from 'react';
import { Link } from 'react-router-dom';
import { Sparkles } from 'lucide-react';
import { useTranslation } from 'react-i18next';
import {
  answerAiConsentPrompt,
  isAiConsentPromptOpen,
  subscribeAiConsentPrompt,
} from '../lib/services/aiConsent.js';

/**
 * One-time permission dialog shown before the first AI request in the native
 * apps (see `lib/services/aiConsent.ts`). Mounted once at the app root.
 */
export const AiConsentDialog = () => {
  const { t } = useTranslation();
  const open = useSyncExternalStore(subscribeAiConsentPrompt, isAiConsentPromptOpen, () => false);

  if (!open) return null;

  return (
    <div
      className="fixed inset-0 bg-black/50 z-[60] flex items-center justify-center p-4"
      role="dialog"
      aria-modal="true"
      aria-labelledby="ai-consent-title"
      data-testid="ai-consent-dialog"
    >
      <div className="bg-white rounded-2xl shadow-xl max-w-md w-full p-6 max-h-[90vh] overflow-y-auto">
        <div className="flex items-center gap-3 mb-4">
          <div className="w-10 h-10 rounded-full bg-blue/10 flex items-center justify-center shrink-0">
            <Sparkles className="w-5 h-5 text-blue" />
          </div>
          <h2 id="ai-consent-title" className="text-xl font-serif font-bold text-ink">
            {t('aiConsent.title', 'Allow AI features?')}
          </h2>
        </div>

        <div className="space-y-3 mb-6 text-[14px] text-ink2 leading-relaxed">
          <p>
            {t(
              'aiConsent.body',
              'Word explanations, the tutor, sentence analysis, photo import and pronunciation feedback are generated by Google Gemini, a third-party AI service.'
            )}
          </p>
          <p>
            {t(
              'aiConsent.dataShared',
              'When you use them, what you submit — the text you are reading or importing, your questions, photos of pages and voice recordings — is sent to Google to produce the answer.'
            )}
          </p>
          <p className="text-[13px] text-muted">
            {t(
              'aiConsent.changeLater',
              'You can change this at any time in Settings → Privacy. Reading, vocabulary and reviews work without it.'
            )}{' '}
            <Link to="/privacy" className="text-blue underline">
              {t('aiConsent.privacyLink', 'Privacy Policy')}
            </Link>
          </p>
        </div>

        <div className="flex gap-3">
          <button
            type="button"
            onClick={() => answerAiConsentPrompt(false)}
            className="flex-1 px-4 py-3 border border-bdr rounded-lg font-bold text-[14px] hover:bg-parch transition-colors"
            data-testid="ai-consent-decline"
          >
            {t('aiConsent.decline', 'Not now')}
          </button>
          <button
            type="button"
            onClick={() => answerAiConsentPrompt(true)}
            className="flex-1 px-4 py-3 rounded-lg font-bold text-[14px] text-white bg-blue hover:opacity-90 transition-opacity"
            data-testid="ai-consent-allow"
          >
            {t('aiConsent.allow', 'Allow')}
          </button>
        </div>
      </div>
    </div>
  );
};
