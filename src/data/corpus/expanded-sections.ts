function sent(
  id: string,
  words: string[],
  translation: string,
  lemmaMap?: Record<string, { lemma: string; gloss: string; partOfSpeech?: string }>
): Sentence {
  return {
    id,
    tokens: words.map((w, i) => {
      const clean = w.replace(
        /^[\s!@#$%^&*()\-_=+[\]{}|;:',.<>?/~`"«»‹›‎‏׀׃]+|[\s!@#$%^&*()\-_=+[\]{}|;:',.<>?/~`"«»‹›‎‏׀׃]+$/g,
        ''
      );
      const punctAfter = w.replace(clean, '') || ' ';
      // Strip Hebrew cantillation accents (U+0591-U+05AF, U+05BD-U+05C7) but
      // keep Hebrew vowel points (U+05B0-U+05BC) so lex keys with vowels match.
      const noCantillation = clean
        .normalize('NFD')
        .replace(/[\u0591-\u05af\u05bd-\u05c7]/g, '');
      const normalized = clean
        .normalize('NFD')
        .replace(/[\u0300-\u036f\u0591-\u05c7]/g, '')
        .toLowerCase();
      const mapped =
        lemmaMap?.[clean] ||
        lemmaMap?.[noCantillation] ||
        lemmaMap?.[normalized] ||
        HEB_LEXICON[clean] ||
        HEB_LEXICON[noCantillation] ||
        GEN_LEX[normalized] ||
        GRC_MINI_LEX[normalized] ||
        LXX_LEX[normalized] ||
        LAT_MINI_LEX[normalized] ||
        CLASSICAL_GRC_LEX[normalized] ||
        CLASSICAL_LAT_LEX[normalized];
      return {
        id: `${id}-t${i}`,
        surface: w,
        normalized,
        lemma: mapped?.lemma || normalized,
        gloss: mapped?.gloss || '',
        morphology: { partOfSpeech: mapped?.partOfSpeech || 'unknown' },
        punctBefore: i === 0 ? '' : ' ',
        punctAfter: punctAfter ? punctAfter + ' ' : ' ',
      };
    }),
    translation,
  };
}

